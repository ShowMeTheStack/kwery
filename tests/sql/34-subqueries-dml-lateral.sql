-- DELETE with subqueries
delete from tx where acct not in (select id from acct) returning id;
delete from tx where acct is null or not exists (select 1 from acct where acct.id = tx.acct) returning id;
delete from acct where id in (select id from acct where owner like 'g%') returning id;
delete from acct a using tx where tx.acct = a.id and tx.kind = 'int' and a.id > 10 returning a.id;
delete from acct where bal = (select min(bal) from acct) returning id, bal;
delete from tx where amt < (select avg(amt) from tx) returning acct, amt;
