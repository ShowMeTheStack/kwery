update prices p set price = price + c.delta from changes c where c.id = p.id and c.id <> 2 returning p.id, p.price, c.delta;
update prices set price = price * 2 from (select id from changes where delta > 0) x where x.id = prices.id returning prices.*;
update prices set price = 0 from changes where changes.id = 99;
select * from prices order by id;
update prices set price = price + 1 from changes c join (values (1), (2)) v(i) on v.i = c.id where prices.id = c.id and c.delta > 0;
select * from prices order by id;
