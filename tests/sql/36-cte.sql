with co_total as (select company_id, sum(fee) total from artist group by company_id), avg_total as (select avg(total) a from co_total) select company_id from co_total, avg_total where total > a order by 1;
with rich as (select company_id from company where budget > 800000) select person_id from artist where company_id in (select company_id from rich) order by person_id;
with c as (select perf_id, count(*) n from booking group by perf_id) select perf_id, n from c where n = (select max(n) from c);
with s as (select patron_id, name, points from patron where city = (select min(city) from patron)) select s1.patron_id, s2.patron_id from s s1 join s s2 on s1.points = s2.points and s1.patron_id < s2.patron_id;
with ranked as (select person_id, company_id, fee, rank() over (partition by company_id order by fee desc) r from artist) select company_id, person_id from ranked where r = 1 order by 1 nulls first, 2;
with months as (select distinct date_trunc('month', perf_date) m from performance) select m.m, count(b.booking_id) from months m left join performance pf on date_trunc('month', pf.perf_date) = m.m left join booking b using (perf_id) group by m.m order by 1;
with mentees as (select mentor_id, count(*) n from mentor group by mentor_id) select a.person_id, coalesce(m.n, 0) from artist a left join mentees m on m.mentor_id = a.person_id where a.company_id = (select min(company_id) from company) order by 1;
