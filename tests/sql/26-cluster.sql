-- CLUSTER: rows rewritten in index order, the clustered index remembered, correlation after ANALYZE
create table cl (id int primary key, k int, s text);
insert into cl select g, (g * 7919) % 100, 'v' || g from generate_series(1, 300) g;
create index cl_k on cl (k desc, id);
create index cl_h on cl using hash (s);
cluster cl;
cluster cl using cl_k;
select ctid, k, id from cl limit 5;
analyze cl;
select attname, correlation from pg_stats where tablename = 'cl' order by 1;
cluster cl using cl_h;
cluster cl using nope;
create table other (a int primary key);
cluster cl using other_pkey;
alter table cl cluster on cl_pkey;
cluster cl;
select ctid, id from cl limit 3;
analyze cl;
select attname, correlation from pg_stats where tablename = 'cl' and attname = 'id';
cluster;
alter table cl set without cluster;
cluster cl;
select count(*), sum(k) from cl where k between 10 and 20;
select id from cl where id = 150;
select k, count(*) from cl where k > 95 group by k order by k;
cluster cl using cl_k;
update cl set s = 'u' where id <= 3;
select id, s from cl where id <= 4 order by id;
create index cl_expr on cl ((k % 10), id);
cluster cl using cl_expr;
select k % 10, id from cl limit 4;
create index cl_part on cl (k) where k > 50;
cluster cl using cl_part;
begin;
cluster cl using cl_pkey;
select ctid, id from cl limit 2;
rollback;
select ctid, k % 10 from cl limit 2;
