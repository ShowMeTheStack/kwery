insert into cl2 select g % 17, 'x' || g from generate_series(1, 100) g;
create index cl2_a on cl2 (a);
cluster cl2 using cl2_a;
select a, count(*) from cl2 group by a order by a limit 3;
analyze cl2;
select attname, correlation from pg_stats where tablename = 'cl2' and attname = 'a';
cluster cl2;
