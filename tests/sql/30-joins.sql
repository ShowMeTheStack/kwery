-- joins of every kind on small tables with NULL keys, then on the theatre data
create table l (k int, a text);
create table r (k int, b text);
insert into l values (1, 'l1'), (2, 'l2'), (2, 'l2b'), (null, 'lnull'), (4, 'l4');
insert into r values (2, 'r2'), (3, 'r3'), (null, 'rnull'), (4, 'r4'), (4, 'r4b');
select * from l join r on l.k = r.k;
select * from l inner join r on l.k = r.k order by l.a, r.b;
select * from l left join r on l.k = r.k;
select * from l left outer join r on l.k = r.k order by l.a, r.b nulls first;
select * from l right join r on l.k = r.k;
select * from l full join r on l.k = r.k;
select * from l full outer join r on l.k = r.k order by l.a nulls last, r.b nulls last;
select * from l cross join r;
select count(*) from l, r;
select * from l join r using (k);
select * from l left join r using (k);
select * from l right join r using (k);
select * from l full join r using (k);
select k, a, b from l full join r using (k) order by k nulls first, a, b;
select * from l natural join r;
select * from l natural left join r;
select * from l natural full join r;
select * from l join r on l.k is not distinct from r.k;
select * from l left join r on l.k = r.k and r.b <> 'r4';
select * from l left join r on l.k = r.k where r.b is null;
select * from l left join r on true;
select * from l join r on false;
select * from l left join r on false;
select * from l full join r on false;
select * from l join r on l.k < r.k;
select * from l join r on l.k between r.k - 1 and r.k;
select * from l join r on l.k + 1 = r.k;
select * from l join r on coalesce(l.k, 0) = coalesce(r.k, 0);
select * from l join r on l.a < r.b;
select * from l full join r on l.k = r.k and l.a = 'l2';
select * from l full join r on l.k < r.k;
select l1.a, l2.a from l l1 join l l2 on l1.k = l2.k and l1.a < l2.a;
select l1.a, l2.a from l l1 left join l l2 on l1.k = l2.k and l1.a <> l2.a;
select * from l, lateral (select * from r where r.k = l.k) x;
select * from l left join lateral (select b from r where r.k > l.k order by b limit 1) x on true;
select * from l cross join lateral (select count(*) as c from r where r.k <= l.k) x;
select * from l, lateral (select l.k * 10 as kk) x;
select * from (l join r on l.k = r.k) j;
select * from (l join r using (k)) as j(kk, aa, bb);
select * from l join (r join l l2 on r.k = l2.k) on l.k = r.k;
select * from (l left join r on l.k = r.k) left join l l3 on l3.k = r.k;
select * from l left join (r join l l2 on r.k = l2.k) on l.k = r.k;
select count(*) from l a join l b on true join l c on true;
select * from l join r on l.k = r.k join l l3 on l3.a = l.a;
select * from l right join r on l.k = r.k left join l l3 on l3.k = l.k;
select * from l full join r on l.k = r.k full join l l3 on l3.k = r.k;
select l.k, r.k, count(*) from l full join r on l.k = r.k group by l.k, r.k;
select * from l where exists (select 1 from r where r.k = l.k);
select * from l where not exists (select 1 from r where r.k = l.k);
