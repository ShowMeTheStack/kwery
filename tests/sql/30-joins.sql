-- theatre data
select a.billed_as, c.name from artist a join company c on a.company_id = c.company_id;
select a.billed_as, c.city from artist a join company c using (company_id) where c.budget > 500000;
select c.name, count(a.person_id) from company c left join artist a on a.company_id = c.company_id group by c.name;
select c.name, count(*) from company c left join artist a on a.company_id = c.company_id group by c.name;
select p.given_name, p.family_name, a.fee from person p join artist a using (person_id) where a.company_id is null;
select p.person_id from person p left join artist a on a.person_id = p.person_id where a.person_id is null;
select count(*) from patron natural join booking;
select count(*) from patron p join booking b on p.patron_id = b.patron_id;
select count(*) from patron p left join booking b on p.patron_id = b.patron_id;
select count(*) from booking b right join patron p on p.patron_id = b.patron_id;
select count(*) from booking b full join patron p on p.patron_id = b.patron_id;
select pr.prod_id, pr.based_on, src.title from production pr join production src on src.prod_id = pr.based_on;
select pr.prod_id, src2.prod_id from production pr join production src on src.prod_id = pr.based_on join production src2 on src2.prod_id = src.based_on;
select pr.title, src.title from production pr left join production src on src.prod_id = pr.based_on where pr.genre = 'drama';
select m.mentor_id, m.mentee_id, mm.mentee_id from mentor m join mentor mm on mm.mentor_id = m.mentee_id;
select a1.person_id, a2.person_id from artist a1 join artist a2 on a1.company_id = a2.company_id and a1.fee > a2.fee where a1.company_id = (select min(company_id) from company);
select a1.person_id, count(a2.person_id) from artist a1 left join artist a2 on a2.fee > a1.fee group by a1.person_id;
select pf.perf_id, v.venue_name, s.seats from performance pf join stage s using (venue_code, stage_no) join venue v using (venue_code) where pf.prod_id in (select prod_id from production where genre = 'opera');
select count(*) from performance pf join stage s on s.venue_code = pf.venue_code and s.stage_no = pf.stage_no;
select count(*) from performance pf left join stage s on s.venue_code = pf.venue_code and s.stage_no = pf.stage_no and s.kind = 'thrust';
select count(*) from stage s left join performance pf on pf.venue_code = s.venue_code and pf.stage_no = s.stage_no and pf.perf_date >= date '2025-01-01';
select x.city, x.n, y.n from (select city, count(*) n from patron group by city) x full join (select home_city as city, count(*) n from person group by home_city) y using (city);
select x.city, x.n, y.n from (select city, count(*) n from patron group by city) x full join (select home_city, count(*) n from person group by home_city) y on x.city is not distinct from y.home_city;
select c.name, s.cnt from company c cross join lateral (select count(*) cnt from production pr where pr.company_id = c.company_id) s;
select c.name, t.billed_as, t.fee from company c left join lateral (select billed_as, fee from artist a where a.company_id = c.company_id order by fee desc, person_id limit 2) t on true;
select a.city, b.city from (select distinct city from venue) a join (select distinct city from company) b on a.city < b.city;
select count(*) from booking b1 join booking b2 on b1.perf_id = b2.perf_id and b1.patron_id < b2.patron_id;
select b.booking_id, b.paid from patron p join booking b on p.patron_id = b.patron_id and b.rating is null where p.city is null;
select pr.title from production pr left join performance pf on pf.prod_id = pr.prod_id where pf.perf_id is null;
select s.venue_code, s.stage_no, count(pf.perf_id) from stage s left join performance pf using (venue_code, stage_no) group by s.venue_code, s.stage_no;
select * from company c join stage s on s.seats * 2000 > c.budget where c.founded < 1980;
select c.name from company c join artist a on a.company_id = c.company_id join casting cs on cs.person_id = a.person_id group by c.name having count(distinct cs.prod_id) > 3;
select count(*) from artist join casting using (person_id) join production using (prod_id) join performance using (prod_id) join stage using (venue_code, stage_no) join venue using (venue_code);
select count(*) from venue join stage using (venue_code) join performance using (venue_code, stage_no) join production using (prod_id) join casting using (prod_id) join artist using (person_id);
select count(*) from casting cs join artist a using (person_id) join company c on c.company_id = a.company_id join production pr on pr.prod_id = cs.prod_id and pr.company_id <> c.company_id;
select p.given_name, p2.given_name from mentor m join person p on p.person_id = m.mentor_id join person p2 on p2.person_id = m.mentee_id join artist a1 on a1.person_id = m.mentor_id join artist a2 on a2.person_id = m.mentee_id and a2.company_id is distinct from a1.company_id;
