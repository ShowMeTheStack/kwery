// ---- a tiny evaluator for the test expressions: f(args), a OP b, OP a, 'text'::type, numbers, NULL, ( ) ------------
function lex(s) {
  const out = [];
  for (let i = 0; i < s.length;) {
    const c = s[i];
    if (/\s/.test(c)) { i++; continue; }
    if (c === "'") {
      let j = i + 1, v = '';
      for (;;) { if (s[j] === "'" && s[j + 1] === "'") { v += "'"; j += 2; } else if (s[j] === "'") break; else v += s[j++]; }
      out.push({ t: 'str', v }); i = j + 1; continue;
    }
    if (s.startsWith('::', i)) { out.push({ t: '::' }); i += 2; continue; }
    if ('(),[]'.includes(c)) { out.push({ t: c }); i++; continue; }
    const n = /^\d+(\.\d*)?([eE][+-]?\d+)?/.exec(s.slice(i));
    if (n) { out.push({ t: 'num', v: n[0] }); i += n[0].length; continue; }
    const w = /^[A-Za-z_][A-Za-z_0-9]*/.exec(s.slice(i));
    if (w) { out.push({ t: 'id', v: w[0] }); i += w[0].length; continue; }
    const o = /^[+\-*/<>=~!@#%^&|?]+/.exec(s.slice(i));
    if (o) { out.push({ t: 'op', v: o[0] }); i += o[0].length; continue; }
    throw new Error('cannot lex ' + s.slice(i));
  }
  return out;
}
function parse(src) {
  const toks = lex(src);
  let i = 0;
  const peek = (t) => toks[i] && toks[i].t === t;
  const typeName = () => {
    let n = toks[i++].v;
    while (peek('id') && /^(precision|with|without|time|zone|varying)$/i.test(toks[i].v)) n += ' ' + toks[i++].v;
    const mods = [];
    if (peek('(')) { i++; while (!peek(')')) { if (peek('num')) mods.push(+toks[i].v); i++; } i++; }
    let t = K.T.byName(n, mods);
    while (peek('[')) { i += 2; t = K.T.arrayOf(t); }
    if (!t) throw new Error('unknown type ' + n);
    return t;
  };
  const arrayBody = () => { const items = []; while (!peek(']')) { if (peek('[')) { i++; items.push(arrayBody()); } else items.push(expr()); if (peek(',')) i++; } i++; return { k: 'array', items }; };
  const casts = (e) => { while (peek('::')) { i++; e = { k: 'cast', e, type: typeName() }; } return e; };
  const primary = () => {
    const t = toks[i++];
    if (t.t === 'str') return casts({ k: 'lit', v: t.v });
    if (t.t === 'num') return casts({ k: 'num', v: t.v });
    if (t.t === '(') { const e = expr(); i++; return casts(e); }
    if (t.t === 'op') return { k: 'un', op: t.v, e: primary() };
    if (t.t === 'id' && /^null$/i.test(t.v)) return casts({ k: 'null' });
    if (t.t === 'id' && /^(true|false)$/i.test(t.v)) return casts({ k: 'bool', v: /^true$/i.test(t.v) });
    if (t.t === 'id' && /^array$/i.test(t.v)) { i++; return casts(arrayBody()); }
    if (t.t === 'id' && /^row$/i.test(t.v)) { i++; const items = []; while (!peek(')')) { items.push(expr()); if (peek(',')) i++; } i++; return casts({ k: 'row', items }); }
    if (t.t === 'id' && peek('(')) { i++; const args = []; while (!peek(')')) { args.push(expr()); if (peek(',')) i++; } i++; return casts({ k: 'call', name: t.v.toLowerCase(), args }); }
    throw new Error('cannot parse at ' + JSON.stringify(t) + ' in ' + src);
  };
  const expr = () => { let l = primary(); while (peek('op')) { const op = toks[i++].v; l = { k: 'op', op, l, r: primary() }; } return l; };
  const e = expr();
  if (i < toks.length) throw new Error('trailing tokens in ' + src);
  return e;
}
const unknown = (x) => x.t.cat === 'P';
const toType = (x, t, ctx) => {
  if (!t || (t.cat === 'P' && t.id !== 'unknown')) return x.v;
  if (x.v === null) return null;
  if (unknown(x)) return K.T.input(x.v, t, ctx);
  if (x.t.id === t.id && (t.cat !== 'A' || x.t.elem.id === t.elem.id)) return x.v;
  return K.T.cast(x.v, x.t, t, false, ctx);
};
function call(def, r, args, ctx) {
  const vals = args.map((a, i) => toType(a, r.argTypes[i], ctx));
  if (def.strict !== false && vals.some((v) => v === null)) return { v: null, t: r.ret };
  return { v: def.fn(vals, ctx, { rt: r.ret, at: r.argTypes, node: {} }), t: r.ret };
}
function ev(n, ctx) {
  switch (n.k) {
    case 'lit': return { v: n.v, t: B.unknown };
    case 'null': return { v: null, t: B.null };
    case 'bool': return { v: n.v, t: B.bool };
    case 'num': {
      if (/[.eE]/.test(n.v)) return { v: K.Decimal.parse(n.v), t: B.numeric };
      const b = BigInt(n.v);
      return b <= 2147483647n ? { v: Number(b), t: B.int4 } : b < 2n ** 63n ? { v: b, t: B.int8 } : { v: K.Decimal.parse(n.v), t: B.numeric };
    }
    case 'cast': { const x = ev(n.e, ctx); return { v: unknown(x) ? K.T.input(x.v, n.type, ctx) : K.T.cast(x.v, x.t, n.type, true, ctx), t: n.type }; }
    case 'array': {
      const xs = n.items.map((x) => ev(x, ctx));
      if (xs.length && xs.every((x) => x.t.cat === 'A')) return { v: new K.ArrayV(xs.map((x) => x.v)), t: xs[0].t };
      const et = K.T.common(xs.map((x) => x.t));
      return { v: new K.ArrayV(xs.map((x) => toType(x, et, ctx))), t: K.T.arrayOf(et) };
    }
    case 'row': {
      const xs = n.items.map((x) => ev(x, ctx)).map((x) => (unknown(x) && x.t.id !== 'null' ? { v: x.v, t: B.text } : x));
      return { v: new K.RowV(xs.map((x) => x.v)), t: { id: 'record', name: 'record', cat: 'C', len: -1, fields: xs.map((x, i) => ({ name: 'f' + (i + 1), type: x.t })) } };
    }
    case 'call': {
      const args = n.args.map((a) => ev(a, ctx));
      const list = K.F.FUNCS.get(n.name);
      const r = list && K.F.resolve(list, args.map((a) => a.t), n.name);
      if (!r) throw K.err('42883', 'function ' + n.name + '(' + args.map((a) => K.T.sqlName(a.t)).join(', ') + ') does not exist');
      return call(r.def, r, args, ctx);
    }
    case 'un': {
      const x = ev(n.e, ctx);
      if (n.op === '-') { const t = unknown(x) ? B.numeric : x.t; const v = toType(x, t, ctx); return { v: v === null ? null : typeof v === 'bigint' ? -v : v instanceof K.Decimal ? v.neg() : v instanceof K.IntervalV ? v.neg() : -v, t }; }
      const list = K.F.OPS.get('u' + n.op);
      const r = list && K.F.resolve(list, [x.t]);
      if (!r) throw K.err('42883', 'operator does not exist: ' + n.op + ' ' + K.T.sqlName(x.t));
      return call(r.def, r, [x], ctx);
    }
    case 'op': {
      const a = ev(n.l, ctx), b = ev(n.r, ctx);
      const num = (x) => x.t.cat === 'N' || unknown(x);
      const list = K.F.OPS.get(n.op);
      // || goes to the registry only for arrays, json and bytea, as the binder does
      const viaOps = n.op !== '||' || a.t.cat === 'A' || b.t.cat === 'A' || (a.t.cat === 'J' && b.t.cat === 'J') || (a.t.cat === 'X' && b.t.cat === 'X');
      const r = viaOps && list && K.F.resolve(list, [a.t, b.t]);
      if ('+-*/%'.includes(n.op) && n.op.length === 1 && num(a) && num(b) && !(r && r.def.special)) {
        const t = K.F.numResult(unknown(a) ? undefined : a.t, unknown(b) ? undefined : b.t);
        const x = toType(a, t, ctx), y = toType(b, t, ctx);
        return { v: x === null || y === null ? null : K.F.arith(n.op, x, y, t), t };
      }
      if (n.op === '||' && !r) { const x = toType(a, B.text, ctx), y = toType(b, B.text, ctx); return { v: x === null || y === null ? null : String(x) + String(y), t: B.text }; }
      if (!r) throw K.err('42883', 'operator does not exist: ' + K.T.sqlName(a.t) + ' ' + n.op + ' ' + K.T.sqlName(b.t));
      return call(r.def, r, [a, b], ctx);
    }
  }
  throw new Error('bad node ' + n.k);
}
function run(src, zone) {
  const ctx = { zone: zone || 'UTC', session: { settings: { timezone: zone || 'UTC' } } };
  try {
    const r = ev(parse(src), ctx);
    const o = K.T.output(r.v, r.t, ctx);
    return o === null ? '<NULL>' : o;
  } catch (e) {
    if (e instanceof K.DBError) return 'ERROR ' + e.code + ': ' + e.message;
    throw e;
  }
}

let pass = 0, fail = 0;
function check(name, got, want) {
  if (got === want) { pass++; return; }
  fail++;
  console.log('FAIL ' + name + '\n  want: ' + JSON.stringify(want) + '\n  got:  ' + JSON.stringify(got));
}

